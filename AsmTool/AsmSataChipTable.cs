		public static AsmSataChip? Find(byte j0, byte j1, byte j2) {
			foreach (var c in Chips) {
				if (c.Jedec0 == j0 && c.Jedec1 == j1 && c.Jedec2 == j2) {
					return c;
				}
			}
			return null;
		}
